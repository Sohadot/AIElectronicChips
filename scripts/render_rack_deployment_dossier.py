#!/usr/bin/env python3
"""Render the AI rack deployment verification dossier (IDE-014) and its expert-review brief.

Both are generated from data/research/institutional/rack-deployment-verification-dossier-014.json and the
corpus it builds on: evidence states and statuses come from the IDE-006 dossier and reference pathway C,
requirement details from IDE-010 workflow C, and inspection results from the inspection log. Neither file
is deployed.

    python3 scripts/render_rack_deployment_dossier.py          # rewrite both documents
    python3 scripts/render_rack_deployment_dossier.py --check  # fail if either is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate_rack_deployment_dossier as v  # noqa: E402

OUT = ROOT / "AI_RACK_DEPLOYMENT_VERIFICATION_DOSSIER_014.md"
BRIEF = ROOT / "RACK_DEPLOYMENT_EXPERT_REVIEW_BRIEF_014.md"
HEADER = ("<!-- Generated by scripts/render_rack_deployment_dossier.py from "
          "data/research/institutional/rack-deployment-verification-dossier-014.json. Do not edit by hand. -->")
DOMAIN_LABEL = {"compute_hardware": "Compute hardware and configuration", "electrical": "Electrical infrastructure",
                "thermal": "Thermal and liquid cooling", "network_interconnect": "Networking and interconnect",
                "software": "Firmware and software", "facility_operations": "Facility operations and monitoring",
                "access_compliance": "Access and regulatory conditions"}
BASIS_LABEL = {"published": "published", "derived_from_published": "derived from published sources", "project_defined": "project-defined"}


def word(s) -> str:
    return str(s).replace("_", " ")


def cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def codes(ids) -> str:
    return ", ".join(f"`{x}`" for x in ids) or "—"


def highest(states) -> str:
    ranked = [s for s in states if s in v.RANK]
    return max(ranked, key=v.rank) if ranked else "not_established"


def latest(log) -> dict[str, dict]:
    order = {r["run_id"]: i for i, r in enumerate(log["runs"])}
    out: dict[str, dict] = {}
    for rec in log["records"]:
        if rec["source_id"] not in out or order[rec["run_id"]] >= order[out[rec["source_id"]]["run_id"]]:
            out[rec["source_id"]] = rec
    return out


def render_dossier(d, ctx) -> str:
    reqs = {q["id"]: q for q in ctx["ide006"]["requirements"]}
    types = {t["id"]: t for t in d["record_types"]}
    wf = next(w for w in ctx["workbench"]["workflows"] if w["id"] == d["inputs"]["workflow_id"])
    rcs = {r["id"]: r for r in wf["requirements"]}
    pathway = next(p for p in ctx["pathways"]["pathways"] if p["id"] == d["inputs"]["pathway_id"])
    ladder = {row["state"]: row for row in pathway["evidence_ladder"]}
    unresolved = {u["id"]: u for r in ctx["releases"].values() for u in r["unresolved"]}
    reg, last = ctx["registry"], latest(ctx["log"])
    site_sources = [s for s, rec in reg.items() if v.SITE_CLAIM in rec.get("supported_claim_types", [])]

    def public_state(req_ids) -> str:
        return highest(reqs[x]["current_state"] for x in req_ids)

    out = [HEADER, "", "# AI Rack Deployment — Evidence Chain & Operational Verification Dossier", "",
           f"- **Dossier:** `{d['dossier_id']}` (release {d['release']}, schema {d['schema_version']}), as of {d['as_of']}.",
           f"- **Status:** research candidate; not reviewed; scientific review {d['scientific_review']}; review owner {d['review_owner']}.",
           f"- **Method:** AI-assisted source check. Interpretation standard: {d['interpretation_standard']}.",
           f"- **Builds on:** `{d['inputs']['release_id']}` (22 findings, nine evidence states), `{d['inputs']['dossier_id']}` "
           f"({len(reqs)} domain requirements), IDE-010 `{d['inputs']['workflow_id']}` ({len(rcs)} requirements) and reference pathway "
           f"`{d['inputs']['pathway_id']}`.", "", f"> {d['boundary']}", "",
           "## 1. Research question and scope", "", f"**{d['research_question']}**", "",
           f"- **Technical scope:** {d['scope']['technical']}.", f"- **Time:** {d['scope']['temporal']}.", f"- **Site:** {d['scope']['site']}.",
           "- **Excluded:** " + "; ".join(d["scope"]["excluded"]) + ".", "",
           "**What this dossier adds.** Release 006 defines the evidence states and the IDE-006 dossier records where each requirement stands. "
           "This dossier adds the record model between them: which kind of record can support which state, what the record must carry, which "
           "inferences are category errors, and which requirements depend on others.", "",
           "**Principal findings.**", ""]
    out += [f"- {f['text']} Basis: {codes(f['basis'])}." for f in d["findings"]]
    out += ["", "## 2. Evidence states and the records that can support them", "",
            "The nine states are Release 006's. They are not a sequence, different requirements can sit in different states, and one state does not imply another. "
            "A record type's ceiling is the highest state it can support on its own.", "",
            "| State | What it would support (pathway C) | Record types that can reach it | Site record needed |", "| --- | --- | --- | --- |"]
    for s in v.STATES:
        reach = [t for t in d["record_types"] if t["state_ceiling"] == s]
        out.append(f"| {word(s)} | {cell(ladder[s]['supported_statement'])} | {', '.join(t['label'] for t in reach) or '—'} | "
                   f"{'yes' if s in v.SITE_EVIDENCE_STATES else 'no'} |")
    out += [f"| not established | {cell(ladder['not_established']['supported_statement'])} | — | — |", "",
            "### Record admissibility", "",
            "A record counts toward its ceiling only if it carries the attributes listed for its type. The attributes:", ""]
    out += [f"- **{word(k)}:** {v_}." for k, v_ in d["attributes"].items()]
    out += ["", "| Record type | Holder | Ceiling | Site-specific | Must carry | Does not establish | Basis |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for t in d["record_types"]:
        out.append(f"| {cell(t['label'])} (`{t['id']}`) | {cell(t['holder'])} | {word(t['state_ceiling']) if t['state_ceiling'] else 'access dimension'} | "
                   f"{'yes' if t['site_specific'] else 'no'} | {', '.join(word(a) for a in t['required_attributes'])} | {cell(t['does_not_establish'])} | "
                   f"{BASIS_LABEL[t['basis']]}: {codes(t['basis_refs'])} |")
    out += ["", "### Applied to the IDE-006 dossier", "",
            f"Each of the {len(reqs)} IDE-006 requirements was checked against the ceiling of its evidence classification. "
            f"{len(d['ide006_consistency'])} entry records a state above that ceiling:", ""]
    for x in d["ide006_consistency"]:
        out.append(f"- `{x['requirement_id']}`: {word(x['evidence_classification'])} evidence, recorded at {word(x['current_state'])}, "
                   f"ceiling {word(x['state_ceiling'])}. {x['note']}")
        res = x.get("resolution")
        if res:
            pc = res["publication_change"]
            out.append(f"  - **Corrected by {res['resolved_by']}, {res['resolved_at']}:** {word(res['previous_state'])} → "
                       f"{word(res['corrected_state'])}. {res['decision']} Remaining uncertainty: {res['uncertainty_remaining']} "
                       f"Public correction note: `{pc['route']}#{pc['anchor']}`. The flag above is kept as recorded.")
    out += ["", "## 3. Deployment evidence chain", ""]
    for c in d["chain"]:
        letter = c["id"][0].upper()
        out += [f"### {letter}. {c['title']}", "", f"**Question.** {c['question']}", "",
                f"- **States:** {', '.join(word(s) for s in c['states']) or 'none: a separate access dimension'}.",
                f"- **Records:** {', '.join(types[x]['label'] for x in c['record_type_ids'])}.", "- **Category errors:**"]
        out += [f"  - *{e['inference']}.* {e['why_not']}. Basis: {codes(e['basis'])}." for e in c["category_errors"]]
        out.append("")
    out += ["## 4. Seven-domain verification matrix", "",
            "Public state is the highest state the reviewed public sources support for the domain's IDE-006 requirements. "
            f"Site-level state is what the public record shows for any named site: {len(site_sources)} registered sources support a site-record claim.", "",
            "| Domain | Claim investigated | IDE-006 requirements (state) | Public state | Site-level state | Depends on | Acceptance or observation needed | Engineering review |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for dm in d["domains"]:
        dreqs = [q for q in reqs.values() if q["domain"] == dm["id"]]
        listed = "<br>".join(f"`{q['id']}` ({word(q['current_state'])})" for q in dreqs)
        out.append(f"| {DOMAIN_LABEL[dm['id']]} | {cell(dm['claim'])} | {listed} | {word(public_state([q['id'] for q in dreqs]))} | "
                   f"{'not established' if dm['id'] != 'access_compliance' else 'no determination'} | "
                   f"{', '.join(DOMAIN_LABEL[x] for x in dm['depends_on']) or '—'} | {cell(dm['acceptance_or_observation'])} | "
                   f"{'yes' if dm['engineering_review'] else 'no'}: {cell(dm['review_reason'])} |")
    out += ["", "Open questions and register issues by domain:", ""]
    for dm in d["domains"]:
        out.append(f"- **{DOMAIN_LABEL[dm['id']]}:** " + "; ".join(f"`{u}` {unresolved[u]['question']}" for u in dm["unresolved_ids"])
                   + (f" Register: {codes(dm['conflict_ids'])}." if dm["conflict_ids"] else ""))
    out += ["", "## 5. Cross-domain dependencies", "",
            "A dependent requirement cannot hold a site-level state above its prerequisite's. Edges marked project-defined are this project's engineering reading; "
            "the others follow NVIDIA's documented procedure.", "",
            "| Prerequisite | Dependent | Basis | Class |", "| --- | --- | --- | --- |"]
    for e in d["dependencies"]:
        out.append(f"| `{e['prerequisite']}` ({DOMAIN_LABEL[reqs[e['prerequisite']]['domain']]}) | `{e['dependent']}` ({DOMAIN_LABEL[reqs[e['dependent']]['domain']]}) | "
                   f"{codes(e['basis'])} | {BASIS_LABEL[e['basis_class']]} |")
    subject = ctx["ide006"]["subject"]
    out += ["", "## 6. GB200 NVL72 documentary case", "", f"- **System:** {subject['system']}.", f"- **Configuration:** {subject['configuration']}.",
            f"- **Site:** {subject['site']}", "",
            "What each boundary of the chain shows from the reviewed public record:", "",
            "| Boundary | Public documents available | Site records available | Shown |", "| --- | --- | --- | --- |"]
    for c in d["chain"]:
        public = [types[x]["label"] for x in c["record_type_ids"] if not types[x]["site_specific"]]
        shown = ("product and design as NVIDIA describes them" if c["id"] == "a-specification-design"
                 else "the rule text reviewed, no determination" if c["id"] == "g-access" else "not established from the reviewed public record")
        out.append(f"| {c['id'][0].upper()}. {c['title']} | {', '.join(public) or 'none'} | none registered | {shown} |")
    out += ["", "NVIDIA documents what a site must provide and check. No reviewed record shows that any site did it. Where a procedure is cited "
            "(bring-up order, validation tooling, the deployment checklist), it is evidence of the requirement, not of its execution.", "",
            "## 7. Evidence needed for commissioning and acceptance", ""]
    for r in d["matrix"]:
        if r["target_state"] in ("subsystem_commissioned", "integrated_configuration_verified"):
            needed = sorted({a for x in r["record_type_ids"] for a in types[x]["required_attributes"]})
            out.append(f"- **`{r['requirement_id']}` {rcs[r['requirement_id']]['title']}** ({word(r['target_state'])}): "
                       f"{', '.join(types[x]['label'] for x in r['record_type_ids'])}, carrying {', '.join(word(a) for a in needed)}. "
                       f"Conditions: {'; '.join(r['verification_conditions'])}.")
    out += ["", "Acceptance is distinct from technical testing. It needs criteria agreed before testing, an integrated test, and a decision signed by "
            "parties able to accept. A passed subsystem test supplies results for one subsystem; it is not the decision, and it does not show the subsystems work together.", "",
            "## 8. Operational observation and measurement", ""]
    for r in d["matrix"]:
        if r["target_state"] == "operational_performance_observed":
            out.append(f"- **`{r['requirement_id']}` {rcs[r['requirement_id']]['title']}:** {', '.join(types[x]['label'] for x in r['record_type_ids'])}. "
                       f"Conditions: {'; '.join(r['verification_conditions'])}. Would show: {r['supported_inference']}. Would not show: {r['prohibited_inference']}.")
    out += ["", "A peak figure, a published test-suite description or a validated reference design records no site, period or measured result, and none can stand in for observation.", "",
            "## 9. Workflow C coverage", "",
            "Claim → required record → holder → verification conditions → supported inference → prohibited inference → gap, for all "
            f"{len(rcs)} requirements of workflow {wf['letter']}. 'Not obtained' means the record has been neither requested nor reviewed here; "
            "a Workbench collection status is never treated as verification.", "",
            "| Requirement | Claim | Target state | Required record | Holder | Verification conditions | Supported if obtained | Prohibited | Public state | Record | Gap |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for r in d["matrix"]:
        rc = rcs[r["requirement_id"]]
        ps = public_state(r["ide006_requirement_ids"])
        if r["target_state"] in v.SITE_EVIDENCE_STATES:
            ps = "not established"
        out.append(f"| `{rc['id']}` {cell(rc['title'])} ({word(rc['public_availability'])}) | {cell(r['claim'])} | {word(r['target_state'])} | "
                   f"{cell(', '.join(types[x]['label'] for x in r['record_type_ids']))} | {cell(r['holder'])} | {cell('; '.join(r['verification_conditions']))} | "
                   f"{cell(r['supported_inference'])} | {cell(r['prohibited_inference'])} | {word(ps)} | {word(r['record_status'])} | {cell(r['gap'])} |")
    notes = [r for r in d["matrix"] if r["stage_note"]]
    out += ["", "Stage notes, where Workflow C's stage differs from the state the needed record supports (Workflow C is unchanged):", ""]
    out += [f"- `{r['requirement_id']}`: {r['stage_note']}." for r in notes]
    out += ["", "Basis of each row: " + "; ".join(f"`{r['requirement_id']}` {BASIS_LABEL[r['basis_class']]}" for r in d["matrix"]) + ".", "",
            "## 10. Unsupported and unresolved claims", "", "Claims the public record does not support:", ""]
    out += [f"- {e['inference']}." for c in d["chain"] for e in c["category_errors"]]
    open_ids = []
    for dm in d["domains"]:
        open_ids += [u for u in dm["unresolved_ids"] if u not in open_ids]
    out += ["", "Open questions this dossier inherits:", ""]
    out += [f"- `{u}`: {unresolved[u]['question']}" for u in open_ids]
    out += ["", "## 11. Documentary and technical review requirements", "",
            "No review has taken place and no reviewer is assigned. Before any statement here supports a public reference:", "",
            "- a reviewer checks each record type's ceiling and required attributes against the nine-state definitions;",
            "- an engineer reviews each dependency marked project-defined;",
            "- domains marked for engineering review get a specialist reading of the records they would require;",
            "- the stage notes on `rc-07` and `rc-12` are resolved editorially, in Workflow C itself if accepted;",
            "- the questions in `RACK_DEPLOYMENT_EXPERT_REVIEW_BRIEF_014.md` may be put to volunteer specialists, one at a time.", "",
            "## 12. Source lineage, limitations and dates", "",
            "| Source | Publisher | Published | Latest inspection |", "| --- | --- | --- | --- |"]
    sources = sorted({s for r in rcs.values() for s in r["source_ids"]} | {e["source_id"] for q in reqs.values() for e in q["evidence"]})
    for sid in sources:
        rec = last.get(sid)
        pc = rec and rec.get("passage_check")
        state = (f"retrieved {rec['inspected_at']}; {pc['found']} of {pc['quoted_passages']} passages found" if pc
                 else f"{word(rec['states'][-1])} {rec['inspected_at']}" if rec else "not inspected")
        out.append(f"| `{sid}` | {cell(reg[sid]['publisher'])} | {reg[sid].get('publication_date') or reg[sid].get('effective_date') or '—'} | {state} |")
    out += ["", "- Every source is a product description, reference architecture, procedure or regulatory text. None is a site record.",
            "- Passage checks show that quoted text is still published, not that it is correct or that no newer edition exists.",
            "- The record model, ceilings, dependencies and readings are AI-assisted and have not been reviewed by a person.",
            f"- Public reference: {d['public_reference_decision']['reason']}", "",
            "## 13. Research and due-diligence applications", ""]
    out += [f"- {a}." for a in d["applications"]]
    out += ["", "Lineage: judgments in `data/research/institutional/rack-deployment-verification-dossier-014.json`; states and statuses from "
            "`data/research/dossiers/gb200-nvl72-reference-demo.json` and `data/reference-pathways.json`; requirements from "
            "`data/industrial-evidence-requests.json`; validated by `scripts/validate_rack_deployment_dossier.py`; regenerated by "
            "`scripts/render_rack_deployment_dossier.py`.", ""]
    return "\n".join(out)


def render_brief(d, ctx) -> str:
    reg = ctx["registry"]
    out = [HEADER, "", "# Expert Review Brief — AI Rack Deployment Evidence (IDE-014)", "",
           "This brief invites specialists in data-centre electrical, mechanical, network and operations engineering to review one bounded question "
           "each, using public material only. It accompanies `AI_RACK_DEPLOYMENT_VERIFICATION_DOSSIER_014.md`, an AI-assisted research candidate "
           "that no person has reviewed.", "", "## Terms", "",
           "- Participation is voluntary and unpaid. There is no deadline and no obligation to answer every question.",
           "- You may review a single question. Disagreement, criticism and \"this cannot be settled from public material\" are all useful answers.",
           "- Use only public, non-confidential material. Please do not share site records, contracts or anything under NDA.",
           "- You will be named only if you give explicit permission, and only in the form you approve.",
           "- A response is recorded as a specialist's comment on the question it answers. It is not represented as validation, certification or "
           "approval of the dossier, and AI-assisted analysis is never presented as independent human review.", "", "## Questions", ""]
    for n, q in enumerate(d["review_questions"], start=1):
        out += [f"### {n}. {q['question']}", "", f"- **Domain:** {DOMAIN_LABEL[q['domain_id']]}.", f"- **Why it matters:** {q['why_it_matters']}",
                f"- **What would settle it:** {q['would_settle']}.",
                "- **Public materials:** " + "; ".join(f"{reg[s]['publisher']}, “{reg[s]['title']}”, {reg[s]['canonical_url']}" for s in q["materials"]), ""]
    return "\n".join(out)


def outputs() -> dict[Path, str]:
    d, ctx = json.loads(v.DOSSIER.read_text(encoding="utf-8")), v.load_context()
    return {OUT: render_dossier(d, ctx), BRIEF: render_brief(d, ctx)}


def out_of_sync() -> list[str]:
    return [p.name for p, text in outputs().items() if not p.is_file() or p.read_text(encoding="utf-8") != text]


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a document does not match its inputs")
    args = parser.parse_args(argv)
    if args.check:
        stale = out_of_sync()
        if stale:
            print(f"FAIL: out of date: {', '.join(stale)}; run scripts/render_rack_deployment_dossier.py", file=sys.stderr)
            raise SystemExit(1)
        print("PASS: rack deployment dossier and review brief match their inputs.")
        return
    for path, text in outputs().items():
        path.write_text(text, encoding="utf-8")
    print("rack deployment dossier and brief rendered")


if __name__ == "__main__":
    main()
