#!/usr/bin/env python3
"""Validate the evidence-maintenance layer (IDE-008) and generate its impact index.

Three committed files, all offline-checkable (no network in CI):

* data/source-inspections.json: what one inspection run observed for each registered source.
  States are kept separate: metadata validated, source retrieved, content compared, changed,
  inaccessible, review required, not checked. A retrieval is never treated as proof that a claim
  is still correct, and the log never changes registry status or access dates.
* data/evidence-conflicts.json: the conflict register of material contradictions and open
  evidence questions, each tied to sources, findings, unresolved questions, public references and
  pathway steps. It is not an Atlas: it records no dependency relationship.
* data/evidence-impact-index.json: generated by this script (`--write`) from the registry, the
  releases, the public pages, the pathways and the register. For each source it lists what would need
  re-examination if that source changed. It names review targets; it does not promote conclusions.
"""

