from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from validate_dependency_atlas import LAYERS  # noqa: E402
from validate_evidence_releases import (  # noqa: E402
    LEGACY_REFERENCE_PAGES,
    MAX_QUOTE_WORDS,
    NEGATION,
    QUOTED,
    inference_boundary_errors,
    sentences,
)

REGISTRY = ROOT / "data" / "source-registry.json"
INSPECTIONS = ROOT / "data" / "source-inspections.json"
CONFLICTS = ROOT / "data" / "evidence-conflicts.json"
IMPACT = ROOT / "data" / "evidence-impact-index.json"
PATHWAYS = ROOT / "data" / "reference-pathways.json"
DOSSIER_DIR = ROOT / "data" / "research" / "dossiers"
RESEARCH_DIR = ROOT / "data" / "research"
SITEMAP = ROOT / "sitemap.xml"

INSPECTION_STATES = ["metadata_validated", "source_retrieved", "source_content_compared", "source_changed",
                     "source_inaccessible", "review_required", "not_checked"]
CONFLICT_STATES = ["open_conflict", "missing_primary_evidence", "version_scope_difference", "source_access_blocked",
                   "requires_reassessment", "resolved_with_evidence"]
HISTORY_EVENTS = {"registered", "evidence_added", "reassessed", "resolved", "reopened"}
ID_PATTERN = re.compile(r"^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$")
LISTING_PATH = re.compile(r"/(?:press-releases|news|newsroom|media|blog)/?$", re.I)
FORBIDDEN_KEYS = re.compile(
    r"(?i)^(?:reviewer|reviewed_by|reviewed_at|human_review\w*|approved\w*|approval\w*|sign_?off\w*|score\w*|rank\w*|"
    r"freshness_score|risk\w*|probability|urgency\w*|confidence|verified|certif\w*|relation_type|from|to)$")
VERDICT_LANGUAGE = re.compile(
    r"(?i)\b(?:score[sd]?|scoring|rank(?:ed|ing|s)?|risk score|freshness score|\d+(?:\.\d+)?\s?%|"
    r"scientifically reviewed|peer[- ]reviewed|human[- ]reviewed|approved by|certified|fully verified)\b")

# Why a source needs re-examination before current use. A rule of the source type, not a score.
FRESHNESS_BASIS = {
    "government_rule": "Regulatory announcement: check the current consolidated rule text before any current-law statement",
    "regulation": "Legal text: check for amendments and the version in force before any current-law statement",
    "technical_standard": "Standard or specification release: check for later revisions and the normative text",
    "official_technical_disclosure": "Product or technical disclosure: figures and configurations may be revised; recheck before current comparisons",
    "company_announcement": "Dated company statement: historically attributable; recheck before treating as current",
    "company_filing": "Period-bound filing: historically valid for its period; a later filing may supersede it for current use",
    "annual_report": "Period-bound report: historically valid for its period; a later report may supersede it for current use",
    "institutional_report": "Dated estimate or recommendation: recheck for updated editions before current use",
    "peer_reviewed_research": "Dated measurement or analysis: valid for its conditions; check for corrections or newer work",
    "official_dataset": "Dated dataset: check for later releases before current use",
}
PRIORITY_REASONS = [
    ("in_open_conflict", "Cited in an unresolved conflict-register issue"),
    ("multiple_versions_known", "A newer or differing version or edition is recorded"),
    ("product_architecture", "Product architecture statement whose figures may be revised"),
    ("regulatory_current_law", "Regulatory source; current-law text must be checked"),
    ("pending_review", "Registry status is pending_review"),
    ("used_across_releases", "Cited by findings in more than one evidence release"),
    ("used_in_pathways", "Cited by a public research-pathway step"),
]


def nonempty(v) -> bool:
    return isinstance(v, str) and bool(v.strip())


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def iso(value) -> date | None:
    try:
        return date.fromisoformat(value) if isinstance(value, str) else None
    except ValueError:
        return None


def latest_records(inspections: dict) -> dict[str, dict]:
    """The most recent inspection record per source (records are kept for every run; none is overwritten)."""
    out: dict[str, dict] = {}
    for r in inspections.get("records", []):
        if isinstance(r, dict) and (r.get("source_id") not in out or str(r.get("inspected_at")) >= str(out[r["source_id"]].get("inspected_at"))):
            out[r["source_id"]] = r
    return out


def source_date(record: dict) -> date | None:
    return iso(record.get("publication_date") or record.get("effective_date"))


def metadata_issues(record: dict) -> list[str]:
    """Deterministic structural checks on one registry record. Passing them is 'metadata validated' only."""
    issues = []
    for field in ("id", "title", "publisher", "source_type", "canonical_url", "accessed_at", "geographic_scope", "temporal_scope", "status"):
        if not nonempty(record.get(field)):
            issues.append(f"missing {field}")
    published, accessed = source_date(record), iso(record.get("accessed_at"))
    if published is None:
        issues.append("publication_date or effective_date missing or not ISO")
    if accessed is None:
        issues.append("accessed_at missing or not ISO")
    if published and accessed and accessed < published:
        issues.append("accessed_at precedes the source's date")
    url = urlparse(str(record.get("canonical_url", "")))
    if url.scheme != "https" or not url.netloc:
        issues.append("canonical_url is not an https URL")
    elif LISTING_PATH.search(url.path):
        issues.append("canonical_url points to a listing page, not the document")
    for field in ("ontology_layers", "supported_claim_types", "use_limitations"):
        if not isinstance(record.get(field), list) or not record.get(field):
            issues.append(f"{field} must be a non-empty list")
    if set(record.get("ontology_layers") or []) - LAYERS:
        issues.append("ontology_layers outside the governed layers")
    return issues


def release_page_route(release: dict) -> str | None:
    rel = release.get("reference_page", LEGACY_REFERENCE_PAGES.get(release.get("release_id")))
    return "/" + rel[: -len("index.html")] if isinstance(rel, str) else None


def page_ids(route: str) -> set[str]:
    page = ROOT / route.strip("/") / "index.html" if route != "/" else ROOT / "index.html"
    return set(re.findall(r'\bid="([^"]+)"', page.read_text(encoding="utf-8"))) if page.is_file() else set()


def public_pages() -> dict[str, str]:
    out = {}
    for route in re.findall(r"<loc>https://aielectronicchips\.com(/[^<]*)</loc>", SITEMAP.read_text(encoding="utf-8")):
        page = ROOT / route.strip("/") / "index.html" if route != "/" else ROOT / "index.html"
        out[route] = page.read_text(encoding="utf-8")
    return out


def context():
    registry = {s["id"]: s for s in load(REGISTRY)["source_records"]}
    releases = {}
    for p in sorted(RESEARCH_DIR.glob("*.json")):
        r = load(p)
        releases[r["release_id"]] = r
    pathways = load(PATHWAYS)
    dossiers = [load(p) for p in sorted(DOSSIER_DIR.glob("*.json"))]
    return registry, releases, pathways, dossiers


# --- impact index ------------------------------------------------------------------------------------

def build_impact(registry, releases, pathways, dossiers, inspections, conflicts) -> dict:
    pages = public_pages()
    ref_sources = {route: set(re.findall(r'<li id="ref-\d+">.*?<code>([a-z0-9-]+)</code>', html, re.S)) for route, html in pages.items()}
    listed_sources = {route: set(re.findall(r'<li(?: class="pending")?>([a-z0-9-]+)(?: · pending_review)?</li>', html)) for route, html in pages.items()}
    log = latest_records(inspections)
    finding_index = {f["id"]: (rid, f) for rid, r in releases.items() for f in r["findings"]}
    recon_ids: dict[str, list[str]] = {}
    for path in sorted((ROOT / "data").glob("evidence-reconciliations-*.json")):
        for rc in json.loads(path.read_text(encoding="utf-8")).get("reconciliations", []):
            for s in rc.get("source_ids", []):
                recon_ids.setdefault(s, []).append(rc["id"])
    entries = []
    for sid in sorted(registry):
        rec = registry[sid]
        findings = sorted(fid for fid, (rid, f) in finding_index.items() if any(e["source_id"] == sid for e in f["evidence"]))
        by_release = sorted({finding_index[f][0] for f in findings})
        via_findings = sorted({release_page_route(releases[r]) for r in by_release if release_page_route(releases[r])})
        cited = sorted(route for route, ids in ref_sources.items() if sid in ids)
        listed = sorted(route for route, ids in listed_sources.items() if sid in ids and route not in cited)
        unresolved_ctx = sorted(u["id"] for r in releases.values() for u in r["unresolved"] if sid in u.get("sources_checked", []))
        steps = sorted(s["id"] for p in pathways["pathways"] for s in p["steps"] if sid in s["source_ids"])
        comparisons = sorted(c["id"] for p in pathways["pathways"] for c in p.get("comparisons", [])
                             if any(f["finding_id"] in findings for f in c["figures"]))
        dossier_reqs = sorted(r["id"] for d in dossiers for r in d["requirements"] if any(e["source_id"] == sid for e in r["evidence"]))
        issue_ids = sorted(c["id"] for c in conflicts.get("issues", []) if sid in c["source_ids"])
        open_issues = [c for c in conflicts.get("issues", []) if sid in c["source_ids"] and c["state"] != "resolved_with_evidence"]
        reasons = []
        insp = log.get(sid, {})
        if open_issues:
            reasons.append("in_open_conflict")
        if any(sid in c["source_ids"] and c["state"] in {"requires_reassessment", "version_scope_difference", "resolved_with_evidence"}
               for c in conflicts.get("issues", [])):
            reasons.append("multiple_versions_known")
        if rec["source_type"] == "official_technical_disclosure" and findings:
            reasons.append("product_architecture")
        if rec["source_type"] in {"government_rule", "regulation"}:
            reasons.append("regulatory_current_law")
        if rec["status"] == "pending_review":
            reasons.append("pending_review")
        if len(by_release) > 1:
            reasons.append("used_across_releases")
        if steps:
            reasons.append("used_in_pathways")
        revalidate = []
        if findings:
            revalidate.append("Re-read the quoted passages behind each direct finding against the changed source")
        if cited or via_findings:
            revalidate.append("Recheck every statement on the listed reference pages that cites this source")
        if steps:
            revalidate.append("Recheck the listed pathway steps' scope, limitations and evidence class")
        if comparisons:
            revalidate.append("Recheck the listed comparison verdicts and their figures")
        if issue_ids:
            revalidate.append("Reassess the listed conflict-register issues")
        if recon_ids.get(sid):
            revalidate.append("Recheck the public text and pathway values set by the listed reconciliations")
        if not revalidate:
            revalidate.append("No finding, page citation or pathway step rests on this source; record the change in the inspection log")
        entries.append({
            "source_id": sid,
            "status": rec["status"],
            "freshness_basis": FRESHNESS_BASIS[rec["source_type"]],
            "priority_reasons": reasons,
            "latest_inspection": {"inspected_at": insp.get("inspected_at"), "states": insp.get("states", ["not_checked"])},
            "direct": {"findings": findings, "releases": by_release, "reference_pages": sorted(set(cited) | set(via_findings)),
                       "pathway_steps": steps, "comparisons": comparisons, "dossier_requirements": dossier_reqs},
            "contextual": {"unresolved_checked": unresolved_ctx, "listed_on_pages": listed},
            "conflicts": issue_ids,
            "reconciliations": sorted(recon_ids.get(sid, [])),
            "revalidate": revalidate,
            "not_established_by_change": "A change to this source does not by itself change any finding, verdict or pathway; it identifies what must be re-examined.",
        })
    return {
        "index_id": "aec-evidence-impact-index",
        "schema_version": "1.0.0",
        "status": "generated",
        "generated_from": ["data/source-registry.json", "data/research/*.json (findings and unresolved questions only)",
                           "data/research/dossiers/*.json", "data/reference-pathways.json", "data/source-inspections.json",
                           "data/evidence-conflicts.json", "data/evidence-reconciliations-*.json", "public reference pages"],
        "boundary": ("Reference-impact index, not a dependency graph. Each entry names review targets if a source changes; "
                     "candidate Atlas relationships are excluded and nothing here approves or updates a claim."),
        "priority_reason_definitions": dict(PRIORITY_REASONS),
        "sources": entries,
    }


# --- validation --------------------------------------------------------------------------------------

def _walk(obj, path=""):
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield k, f"{path}.{k}", v
            yield from _walk(v, f"{path}.{k}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            yield from _walk(v, f"{path}[{i}]")
    elif isinstance(obj, str):
        yield None, path, obj


def _content_checks(obj, label, leaked: set[str], prose_skip=(".boundary",)) -> list[str]:
    errors = []
    for key, where, value in _walk(obj):
        if key is not None and FORBIDDEN_KEYS.match(str(key)):
            errors.append(f"{label}{where}: field '{key}' is not allowed (no reviewers, approvals, scores or edges)")
        if key is None:
            for token in leaked:
                if token in value:
                    errors.append(f"{label}{where}: names unpublished research candidate '{token}'")
            if ID_PATTERN.fullmatch(value) or any(where.endswith(s) for s in prose_skip):
                continue
            m = VERDICT_LANGUAGE.search(value)
            if m:
                errors.append(f"{label}{where}: score, approval or review-completion language '{m.group(0)}'")
            for sent in sentences(value):
                errors.extend(inference_boundary_errors(sent, f"{label}{where}"))
    return errors


def check_inspections(log: object, registry: dict, today: date) -> list[str]:
    errors = []
    if not isinstance(log, dict) or set(log) != {"log_id", "schema_version", "status", "registry_reference", "boundary",
                                                  "state_definitions", "runs", "records"}:
        return ["source-inspections: top-level fields mismatch"]
    if log["status"] != "maintenance_record":
        errors.append("source-inspections: status must be 'maintenance_record'")
    if list(log["state_definitions"]) != INSPECTION_STATES:
        errors.append(f"source-inspections: state_definitions must define {INSPECTION_STATES} in order")
    runs = {r.get("run_id"): r for r in log["runs"] if isinstance(r, dict)}
    for rid, run in runs.items():
        d = iso(run.get("inspected_at"))
        if d is None or d > today:
            errors.append(f"source-inspections: run {rid} has an invalid or future inspected_at")
        if not nonempty(run.get("method")) or not nonempty(run.get("tool")):
            errors.append(f"source-inspections: run {rid} must state its method and tool")
    seen, seen_pairs = set(), set()
    for i, rec in enumerate(log["records"]):
        where = f"source-inspections.records[{i}]"
        fields = {"source_id", "run_id", "inspected_at", "states", "metadata_issues", "retrievals", "passage_check", "notes", "next_action"}
        if not isinstance(rec, dict) or set(rec) != fields:
            errors.append(f"{where} must contain exactly {sorted(fields)}")
            continue
        sid = rec["source_id"]
        where = f"source-inspections[{sid}]"
        if (sid, rec["run_id"]) in seen_pairs:
            errors.append(f"{where}: duplicate record for run {rec['run_id']}")
        seen_pairs.add((sid, rec["run_id"]))
        seen.add(sid)
        if sid not in registry:
            errors.append(f"{where}: source is not registered")
            continue
        if rec["run_id"] not in runs:
            errors.append(f"{where}: unknown run_id")
        d = iso(rec["inspected_at"])
        if d is None or d > today or (rec["run_id"] in runs and rec["inspected_at"] != runs[rec["run_id"]].get("inspected_at")):
            errors.append(f"{where}: inspected_at must be the run's date and not in the future")
        published = source_date(registry[sid])
        if d and published and d < published:
            errors.append(f"{where}: inspected before the source's own date")
        states = rec["states"]
        if not isinstance(states, list) or not states or any(s not in INSPECTION_STATES for s in states) or len(set(states)) != len(states):
            errors.append(f"{where}: states must be distinct members of {INSPECTION_STATES}")
            continue
        issues = metadata_issues(registry[sid])
        if issues != rec["metadata_issues"]:
            errors.append(f"{where}: metadata_issues do not match the registry record (recomputed {issues})")
        if ("metadata_validated" in states) == bool(issues):
            errors.append(f"{where}: metadata_validated must be present exactly when the record has no metadata issues")
        if issues and "review_required" not in states:
            errors.append(f"{where}: metadata issues require review_required")
        retrieved = [r for r in rec["retrievals"] if isinstance(r, dict) and r.get("outcome") == "retrieved"]
        failed = [r for r in rec["retrievals"] if isinstance(r, dict) and r.get("outcome") == "failed"]
        for r in retrieved:
            if not (isinstance(r.get("http_status"), int) and 200 <= r["http_status"] < 300 and r.get("bytes", 0) > 0 and nonempty(r.get("sha256"))):
                errors.append(f"{where}: a retrieved document needs a 2xx status, a size and a SHA-256")
        if ("source_retrieved" in states) != bool(retrieved):
            errors.append(f"{where}: source_retrieved must be present exactly when a retrieval succeeded")
        if "source_inaccessible" in states and (retrieved or not failed):
            errors.append(f"{where}: source_inaccessible needs a recorded failed attempt and no successful one")
        if "not_checked" in states and (rec["retrievals"] or set(states) - {"not_checked", "metadata_validated", "review_required"}):
            errors.append(f"{where}: not_checked cannot be combined with retrieval states")
        if not rec["retrievals"] and "not_checked" not in states:
            errors.append(f"{where}: with no retrieval attempt the record must say not_checked")
        pc = rec["passage_check"]
        if "source_content_compared" in states:
            if "source_retrieved" not in states or not isinstance(pc, dict) or not pc.get("quoted_passages"):
                errors.append(f"{where}: source_content_compared needs a retrieval and a passage check")
            elif pc.get("not_found") and "review_required" not in states:
                errors.append(f"{where}: passages not found require review_required")
        elif pc is not None:
            errors.append(f"{where}: a passage check is recorded without source_content_compared")
        if "source_changed" in states:
            if "source_content_compared" not in states or not any("change" in n.lower() for n in rec["notes"]):
                errors.append(f"{where}: source_changed needs a content comparison and a note documenting the change")
        if not isinstance(rec["notes"], list) or not nonempty(rec["next_action"]):
            errors.append(f"{where}: notes must be a list and next_action must be stated")
    for sid in sorted(set(registry) - seen):
        errors.append(f"source-inspections: registry source {sid} has no record (use not_checked if it was not inspected)")
    return errors


def check_conflicts(register: object, registry: dict, releases: dict, pathways: dict, inspections: dict, today: date) -> list[str]:
    errors = []
    if not isinstance(register, dict) or set(register) != {"register_id", "schema_version", "status", "scientific_review", "as_of",
                                                            "boundary", "state_definitions", "issues"}:
        return ["evidence-conflicts: top-level fields mismatch"]
    if register["status"] != "maintenance_record" or register["scientific_review"] != "pending":
        errors.append("evidence-conflicts: status must be 'maintenance_record' and scientific_review 'pending'")
    if list(register["state_definitions"]) != CONFLICT_STATES:
        errors.append(f"evidence-conflicts: state_definitions must define {CONFLICT_STATES} in order")
    if "not an Atlas" not in register["boundary"]:
        errors.append("evidence-conflicts: boundary must state that the register is not an Atlas")
    as_of = iso(register["as_of"])
    if as_of is None or as_of > today:
        errors.append("evidence-conflicts: as_of invalid or in the future")
    findings = {f["id"]: rid for rid, r in releases.items() for f in r["findings"]}
    unresolved = {u["id"] for r in releases.values() for u in r["unresolved"]}
    steps = {s["id"] for p in pathways["pathways"] for s in p["steps"]}
    comparisons = {c["id"] for p in pathways["pathways"] for c in p.get("comparisons", [])}
    log = latest_records(inspections)
    fields = {"id", "title", "question", "state", "ontology_layers", "scope", "source_ids", "finding_ids", "unresolved_ids",
              "affected_references", "affected_pathway_steps", "affected_comparisons", "evidence", "posture", "unknown",
              "next_evidence", "inspected_at", "history", "downstream_review"}
    seen = set()
    for i, c in enumerate(register["issues"]):
        if not isinstance(c, dict) or set(c) != fields:
            errors.append(f"evidence-conflicts.issues[{i}] must contain exactly {sorted(fields)}")
            continue
        w = f"evidence-conflicts[{c['id']}]"
        if not ID_PATTERN.fullmatch(str(c["id"])) or c["id"] in seen:
            errors.append(f"{w}: invalid or duplicate id")
        seen.add(c["id"])
        state = c["state"]
        if state not in CONFLICT_STATES:
            errors.append(f"{w}: state must be one of {CONFLICT_STATES}")
            continue
        for field in ("title", "posture", "next_evidence"):
            if not nonempty(c[field]):
                errors.append(f"{w}.{field} must be non-empty")
        if not nonempty(c["question"]) or not c["question"].rstrip().endswith("?"):
            errors.append(f"{w}.question must be a precise question")
        if not isinstance(c["scope"], dict) or set(c["scope"]) != {"product", "temporal"} or not all(nonempty(v) for v in c["scope"].values()):
            errors.append(f"{w}.scope must state product and temporal scope")
        if not c["ontology_layers"] or set(c["ontology_layers"]) - LAYERS:
            errors.append(f"{w}.ontology_layers must be governed layers")
        for sid in c["source_ids"]:
            if sid not in registry:
                errors.append(f"{w}: source {sid} is not registered")
        for fid in c["finding_ids"]:
            if fid not in findings:
                errors.append(f"{w}: finding {fid} does not exist in any release")
        for uid in c["unresolved_ids"]:
            if uid not in unresolved:
                errors.append(f"{w}: unresolved question {uid} does not exist")
        for ref in c["affected_references"]:
            route, _, anchor = str(ref).partition("#")
            if not anchor or anchor not in page_ids(route):
                errors.append(f"{w}: reference {ref} does not resolve to a public section")
        for sid in c["affected_pathway_steps"]:
            if sid not in steps:
                errors.append(f"{w}: pathway step {sid} does not exist")
        for cid in c["affected_comparisons"]:
            if cid not in comparisons:
                errors.append(f"{w}: comparison {cid} does not exist")
        if not c["finding_ids"] and not c["unresolved_ids"]:
            errors.append(f"{w}: an issue must rest on existing findings or unresolved questions")
        inspected = iso(c["inspected_at"])
        if inspected is None or inspected > today:
            errors.append(f"{w}.inspected_at invalid or in the future")
        # Evidence items: quoted from sources this run actually retrieved, on or after the source's date.
        for j, ev in enumerate(c["evidence"]):
            ew = f"{w}.evidence[{j}]"
            if not isinstance(ev, dict) or set(ev) != {"source_id", "locator", "observation"}:
                errors.append(f"{ew} must contain source_id, locator and observation")
                continue
            sid = ev["source_id"]
            if sid not in c["source_ids"]:
                errors.append(f"{ew}: source must be listed in the issue's source_ids")
            if any(len(q.split()) > MAX_QUOTE_WORDS for q in QUOTED.findall(ev["locator"])):
                errors.append(f"{ew}: quoted excerpt exceeds {MAX_QUOTE_WORDS} words")
            retrieved_on = [iso(r["inspected_at"]) for r in inspections.get("records", [])
                            if r.get("source_id") == sid and "source_retrieved" in r.get("states", []) and iso(r.get("inspected_at"))]
            if not retrieved_on:
                errors.append(f"{ew}: evidence must come from a source this inspection retrieved")
            elif inspected and min(retrieved_on) > inspected:
                errors.append(f"{ew}: the issue's inspected_at precedes the source inspection it relies on")
            published = source_date(registry.get(sid, {}))
            if published and inspected and published > inspected:
                errors.append(f"{ew}: source postdates the issue's inspection")
        # History: chronological, never empty, and the provenance of every state.
        hist = c["history"]
        if not isinstance(hist, list) or not hist:
            errors.append(f"{w}.history must record how the issue reached its state")
            hist = []
        dates = [iso(h.get("date")) for h in hist if isinstance(h, dict)]
        if None in dates or dates != sorted(dates) or any(d > today for d in dates if d):
            errors.append(f"{w}.history dates must be valid, ordered and not in the future")
        for h in hist:
            if not isinstance(h, dict) or set(h) != {"date", "event", "detail"} or h.get("event") not in HISTORY_EVENTS or not nonempty(h.get("detail")):
                errors.append(f"{w}.history entries need date, an event in {sorted(HISTORY_EVENTS)} and detail")
        # State-specific rules: no false resolution.
        sources_with_evidence = {ev["source_id"] for ev in c["evidence"] if isinstance(ev, dict)}
        finding_sources = {e["source_id"] for fid in c["finding_ids"] if fid in findings
                           for e in next(f for f in releases[findings[fid]]["findings"] if f["id"] == fid)["evidence"]}
        if state != "resolved_with_evidence" and not (isinstance(c["unknown"], list) and c["unknown"]):
            errors.append(f"{w}: an unresolved issue must state what remains unknown")
        if state == "resolved_with_evidence":
            if not c["evidence"]:
                errors.append(f"{w}: resolved_with_evidence needs primary evidence retrieved in an inspection")
            if not any(h.get("event") == "resolved" for h in hist if isinstance(h, dict)):
                errors.append(f"{w}: resolved_with_evidence needs a 'resolved' history entry explaining why")
            if not c["downstream_review"]:
                errors.append(f"{w}: a resolution must name the public statements to re-examine; it does not rewrite them")
            if not (sources_with_evidence - finding_sources):
                errors.append(f"{w}: a resolution needs evidence beyond the findings that recorded the conflict")
        if state == "open_conflict" and len(finding_sources | sources_with_evidence) < 2:
            errors.append(f"{w}: an open conflict needs at least two sources in disagreement")
        if state == "version_scope_difference" and len(finding_sources | sources_with_evidence) < 2:
            errors.append(f"{w}: a version-scope difference needs at least two dated sources")
        if state == "source_access_blocked" and not any("source_inaccessible" in log.get(s, {}).get("states", []) for s in c["source_ids"]):
            errors.append(f"{w}: source_access_blocked needs a source the inspection recorded as inaccessible")
        if state == "requires_reassessment" and (not c["evidence"] or not c["downstream_review"]):
            errors.append(f"{w}: requires_reassessment needs new evidence and the statements to reassess")
        if state == "missing_primary_evidence" and not NEGATION.search(c["posture"]):
            errors.append(f"{w}: missing_primary_evidence posture must say what is not established")
    return errors


def check_all(today: date | None = None) -> list[str]:
    today = today or date.today()
    registry, releases, pathways, dossiers = context()
    inspections, register = load(INSPECTIONS), load(CONFLICTS)
    leaked = {e["id"] for r in releases.values() for e in r["candidate_relationships"]}
    leaked |= {n["id"] for r in releases.values() for n in r["candidate_nodes"]}
    leaked -= {n["id"] for n in load(ROOT / "data" / "dependency-atlas.json")["nodes"]}
    errors = check_inspections(inspections, registry, today)
    errors += check_conflicts(register, registry, releases, pathways, inspections, today)
    errors += _content_checks(register, "evidence-conflicts", leaked)
    errors += _content_checks(inspections, "source-inspections", leaked, prose_skip=(".boundary", ".url", ".final_url", ".content_type", ".passage"))
    expected = build_impact(registry, releases, pathways, dossiers, inspections, register)
    try:
        if load(IMPACT) != expected:
            errors.append("evidence-impact-index.json is out of date; run scripts/validate_evidence_maintenance.py --write")
    except (OSError, json.JSONDecodeError):
        errors.append("evidence-impact-index.json missing or unreadable; run scripts/validate_evidence_maintenance.py --write")
    for e in expected["sources"]:
        for token in leaked:
            if token in json.dumps(e):
                errors.append(f"evidence-impact-index: names unpublished research candidate '{token}'")
    return errors


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="regenerate data/evidence-impact-index.json")
    args = parser.parse_args(argv)
    if args.write:
        registry, releases, pathways, dossiers = context()
        index = build_impact(registry, releases, pathways, dossiers, load(INSPECTIONS), load(CONFLICTS))
        IMPACT.write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote {IMPACT.relative_to(ROOT)} ({len(index['sources'])} sources)")
        return
    errors = check_all()
    if not errors:
        import render_evidence_maintenance as render  # the /sources/ section is generated from these files
        if not render.in_sync():
            errors.append("sources/index.html maintenance section is out of date; run scripts/render_evidence_maintenance.py")
    if errors:
        for err in errors:
            print(f"FAIL: {err}", file=sys.stderr)
        raise SystemExit(1)
    log, reg = load(INSPECTIONS), load(CONFLICTS)
    retrieved = sum("source_retrieved" in r["states"] for r in log["records"])
    sources = len({r["source_id"] for r in log["records"]})
    print(f"PASS: Evidence maintenance valid ({sources} sources across {len(log['runs'])} runs, {len(log['records'])} records, {retrieved} retrievals; "
          f"{len(reg['issues'])} register issues; impact index in sync).")


if __name__ == "__main__":
    main()
