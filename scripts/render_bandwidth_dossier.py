#!/usr/bin/env python3
"""Render the accelerator bandwidth comparability dossier (IDE-012) and its expert-review brief.

Both documents are generated from data/research/institutional/accelerator-bandwidth-comparability-
dossier-012.json and the corpus it cites: passages, dates and inspection results are read from the
releases, the conflict register, the registry and the inspection log. Neither file is deployed.

    python3 scripts/render_bandwidth_dossier.py          # rewrite both documents
    python3 scripts/render_bandwidth_dossier.py --check  # fail if either is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate_bandwidth_dossier as v  # noqa: E402

OUT = ROOT / "ACCELERATOR_BANDWIDTH_COMPARABILITY_DOSSIER_012.md"
BRIEF = ROOT / "BANDWIDTH_EXPERT_REVIEW_BRIEF_012.md"
HEADER = ("<!-- Generated by scripts/render_bandwidth_dossier.py from "
          "data/research/institutional/accelerator-bandwidth-comparability-dossier-012.json. Do not edit by hand. -->")
CLASS_LABEL = {"comparable_on_documented_terms": "Comparable on documented terms", "conditionally_comparable": "Conditionally comparable",
               "not_comparable": "Not comparable", "indeterminate": "Indeterminate"}
LEVEL_LABEL = {"memory_stack": "memory stack", "device_memory": "device memory", "system_memory_aggregate": "system memory aggregate",
               "device_fabric_link": "fabric link", "device_fabric_aggregate": "device fabric aggregate",
               "superchip_fabric_aggregate": "superchip fabric aggregate", "system_fabric_aggregate": "system fabric aggregate",
               "host_link": "host link", "scale_out_port": "scale-out port"}
COVERAGE = {"addressed": "addressed", "partially_addressed": "partly addressed", "open": "open conflict", "not_available": "no public evidence"}


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def word(value: str) -> str:
    return value.replace("_", " ")


def latest(log) -> dict[str, dict]:
    order = {r["run_id"]: i for i, r in enumerate(log["runs"])}
    out: dict[str, dict] = {}
    for rec in log["records"]:
        if rec["source_id"] not in out or order[rec["run_id"]] >= order[out[rec["source_id"]]["run_id"]]:
            out[rec["source_id"]] = rec
    return out


def inspection(rec) -> str:
    if rec is None:
        return "not inspected"
    if "source_inaccessible" in rec["states"]:
        return f"not retrievable on {rec['inspected_at']}"
    pc = rec["passage_check"]
    return f"retrieved {rec['inspected_at']}" + (f"; {pc['found']} of {pc['quoted_passages']} passages found" if pc else "")


def render_dossier(d, ctx) -> str:
    reg, log = ctx["registry"], json.loads((ROOT / "data" / "source-inspections.json").read_text(encoding="utf-8"))
    last = latest(log)
    figs = {f["id"]: f for f in d["figures"]}
    norms = {n["id"]: n for n in d["normalizations"]}
    rules = {r["id"]: r for r in d["method"]["normalization_rules"]}
    cmps = {c["id"]: c for c in d["comparisons"]}
    wf = next(w for w in ctx["workbench"]["workflows"] if w["id"] == d["inputs"]["workflow_id"])
    reqs = {r["id"]: r for r in wf["requirements"]}
    unresolved = {u["id"]: u for r in ctx["releases"].values() for u in r["unresolved"]}

    def record(f) -> str:
        """The exact passage behind a figure: a quantity's figure is shown through its finding's locator for that source."""
        kind, rel, fid = f["ref"].split(":")[:3]
        if kind == "quantity":
            finding = next(x for x in ctx["releases"][rel]["findings"] if x["id"] == fid)
            return "; ".join(e["locator"] for e in finding["evidence"] if e["source_id"] == f["source_id"])
        if kind == "statement":
            return "Bounded analysis in `" + fid + "`: " + v.resolve(f["ref"], ctx)[1]
        return v.resolve(f["ref"], ctx)[1]

    def fv(fid) -> str:
        f = figs[fid]
        return f"{f['value']} {f['unit']}"

    out = [HEADER, "", "# Accelerator Bandwidth — Evidence, Scope & Comparability Dossier", "",
           f"- **Dossier:** `{d['dossier_id']}` (release {d['release']}, schema {d['schema_version']}), as of {d['as_of']}.",
           f"- **Status:** research candidate; not reviewed; scientific review {d['scientific_review']}; review owner {d['review_owner']}.",
           f"- **Method:** AI-assisted source check. Interpretation standard: {d['interpretation_standard']}.",
           f"- **Evidence base:** releases {', '.join(f'`{r}`' for r in d['inputs']['release_ids'])}; reconciliations "
           + ", ".join(f"`{r}`" for r in d["inputs"]["reconciliation_ids"]) + "; register issues "
           + ", ".join(f"`{c}`" for c in d["inputs"]["conflict_ids"]) + ".", "",
           f"> {d['boundary']}", "",
           "## 1. Research question", "", f"**{d['research_question']}**", "",
           f"- **Scope:** {d['scope']['technical']}.", f"- **Time:** {d['scope']['temporal']}.",
           "- **Excluded:** " + "; ".join(d["scope"]["excluded"]) + ".", "",
           "**Principal findings.**", ""]
    statuses = {f["status"] for f in d["figures"]}
    unstated_dir = sum(1 for f in d["figures"] if f["direction"] == "not_stated")
    out += [f"- None of the {len(d['figures'])} figures is a measurement. Every one is an advertised, specified or calculated peak, or a figure "
            f"whose peak status is not stated ({sum(1 for f in d['figures'] if f['status'] == 'not_stated')}). No workload, software or method accompanies any of them."
            if "measured" not in statuses else "",
            f"- {unstated_dir} of the {sum(1 for f in d['figures'] if f['direction'] != 'not_applicable')} link and fabric figures state no direction; "
            "only one NVIDIA per-GPU NVLink figure does.",
            *[f"- {p['text']} Basis: {', '.join(f'`{b}`' for b in p['basis'])}." for p in d["principal_findings"]],
            f"- Of {len(d['comparisons'])} comparisons classified, "
            + ", ".join(f"{sum(1 for c in d['comparisons'] if c['classification'] == k)} {CLASS_LABEL[k].lower()}" for k in d["method"]["comparability_classes"] if any(c['classification'] == k for c in d['comparisons'])) + ".", ""]
    out = [x for x in out if x is not None]
    out += ["## 2. Metric interpretation method", "",
            "Every figure carries the descriptors below. A descriptor the source does not state is recorded as unknown and is never inferred.", "",
            "| Descriptor | Recorded as |", "| --- | --- |",
            "| Source and locator | The registered source and the exact passage, through the release quantity, register entry or finding that already holds it |",
            "| Product and configuration | As the publisher names them |",
            "| Hierarchy level | memory stack, device memory, system memory aggregate, fabric link, device / superchip / system fabric aggregate, host link, scale-out port |",
            "| Metric, units and counting convention | The publisher's wording and unit; bits and bytes kept apart |",
            "| Direction | bidirectional or per direction only when the source says so; otherwise not stated |",
            "| Aggregation scope | per stack, link, device, superchip or system, or unresolved |",
            "| Topology and conditions | As stated, or unknown |",
            "| Status | advertised, specified or calculated peak; measured; or not stated |",
            "| Evidence class, uncertainty, restrictions | Attributed statement or bounded analysis, and what the figure may not be used for |", "",
            "### Comparability classes", ""]
    for k, text in d["method"]["comparability_classes"].items():
        out.append(f"- **{CLASS_LABEL[k]}.** {text}.")
    out += ["", "These classify metric compatibility. None says which product is faster or better.", "", "### Normalization rules", ""]
    for r in d["method"]["normalization_rules"]:
        req = "; ".join(r["requires"]) or "none"
        rej = "; ".join(r["rejects_when"]) or "none"
        out.append(f"- **`{r['id']}`** — {r['description']} Requires: {req}. Rejected when: {rej}.")
    out += ["", "Each normalization in this dossier is recomputed by the validator, and one that breaks its rule fails the build.", "",
            "## 3. Evidence matrix", "",
            "| Figure | Value | Level | Direction | Scope | Status | Source (date) | Passage | Latest inspection |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for f in d["figures"]:
        s = reg[f["source_id"]]
        direction = word(f["direction"]) + (" (source-stated)" if f["direction_basis"] == "source_stated" else "")
        out.append(f"| `{f['id']}`<br>{cell(f['product'])}: {cell(f['metric'])} | {f['value']} {f['unit']} | {LEVEL_LABEL[f['hierarchy_level']]} | "
                   f"{direction} | {word(f['aggregation_scope'])} | {word(f['status'])} | `{f['source_id']}` ({s.get('publication_date') or 'undated'}) | "
                   f"{cell(record(f))} | {inspection(last.get(f['source_id']))} |")
    out += ["", "Configuration, topology, counting convention, conditions, uncertainty and restrictions for each figure:", ""]
    for f in d["figures"]:
        out.append(f"- **`{f['id']}`** — configuration: {f['configuration']}; topology: {f['topology']}; counting: {f['counting_convention']}; "
                   f"conditions: {f['conditions']}; {word(f['evidence_class'])}. Uncertainty: {'; '.join(f['uncertainty'])}. "
                   f"Restrictions: {'; '.join(f['restrictions'])}.")
    out.append("")
    titles = {"case-a-mi300x": "4", "case-b-rubin-memory": "5", "case-c-nvlink6": "6"}
    for case in d["cases"]:
        c = ctx["issues"][case["conflict_id"]]
        out += [f"## {titles[case['id']]}. Case: {case['title']}", "", f"**Question.** {case['question']}", "",
                f"Register `{case['conflict_id']}`: {word(c['state'])}. Reconciliation `{case['reconciliation_id']}`.", "",
                "**Established by the sources.**", ""]
        out += [f"- {x}." for x in case["established"]]
        out += ["", "**Bounded analysis.**", ""]
        out += [f"- {x}." for x in case["analysis"]]
        out += ["", "**Normalizations used:**", ""]
        for n in d["normalizations"]:
            if n["figure_id"] in case["figure_ids"]:
                out.append(f"- `{n['id']}` ({n['rule_id']}): {fv(n['figure_id'])} → {n['result_value']} {n['result_unit']}. {n['note']}")
        out += ["", "**Comparisons:** " + "; ".join(f"`{x}` {CLASS_LABEL[cmps[x]['classification']].lower()}" for x in case["comparison_ids"]) + ".",
                "", "**Kept as recorded:** " + "; ".join(case["preserved"]) + ".", "",
                "**Open:** " + "; ".join(f"`{u}`: {unresolved[u]['question']}" for u in case["unresolved_ids"]), ""]
    out += ["## 7. Conflicting disclosures and version history", ""]
    for cid in d["inputs"]["conflict_ids"]:
        i = ctx["issues"][cid]
        out.append(f"- **`{cid}`** ({word(i['state'])}). {i['posture']}")
        for h in i.get("history", []):
            out.append(f"  - {h['date']}, {word(h['event'])}: {h['detail']}")
    rec = ctx["reconciliations"]["rc-009-mi300x-infinity-fabric"]
    for p in rec.get("pending_version_verification", []):
        out.append(f"- **Pending version verification:** {p['document']}, edition {p['edition']}. Reported content is not used as evidence here until a version-identified copy is retrieved.")
    out += ["", "## 8. Permitted and prohibited comparisons", ""]
    for k in ("comparable_on_documented_terms", "conditionally_comparable", "not_comparable", "indeterminate"):
        rows = [c for c in d["comparisons"] if c["classification"] == k]
        if not rows:
            continue
        out += [f"### {CLASS_LABEL[k]}", ""]
        for c in rows:
            a, b = c["figure_ids"]
            pw = f" Pathway: `{c['pathway_comparison_id']}`." if c["pathway_comparison_id"] else ""
            if c.get("pathway_divergence"):
                dv = c["pathway_divergence"]
                if dv["status"] == "reconciled":
                    pw += (f" **Divergence from the pathway, reconciled by `{dv['reconciled_by']}`:** reference pathway B recorded "
                           f"`{dv['pathway_comparison_id']}` as {dv['pathway_verdict']}; this dossier classifies it "
                           f"{CLASS_LABEL[dv['dossier_classification']].lower()}. {dv['justification']} The public pathway now records the corrected verdict, "
                           "and the earlier one is kept in the reconciliation record.")
                else:
                    pw += (f" **Divergence from the pathway, {word(dv['status'])}:** reference pathway B still records `{dv['pathway_comparison_id']}` "
                           f"as {dv['pathway_verdict']}; this dossier classifies it {CLASS_LABEL[dv['dossier_classification']].lower()}. {dv['justification']} "
                           "The public pathway is unchanged until it is reconciled in a release.")
            out.append(f"- **`{c['id']}`** — {fv(a)} (`{a}`) against {fv(b)} (`{b}`). {c['reason']}"
                       + (" Conditions: " + "; ".join(c["conditions"]) + "." if c["conditions"] else "")
                       + (" Normalizations: " + ", ".join(f"`{x}`" for x in c["normalization_ids"]) + "." if c["normalization_ids"] else "") + pw)
        out.append("")
    out += ["### Rejected normalizations", ""]
    for r in d["rejected_normalizations"]:
        out.append(f"- **`{r['id']}`** — `{r['rule_id']}` on {fv(r['figure_id'])} (`{r['figure_id']}`): {r['why']}")
    out += ["", "## 9. Unresolved questions and missing evidence", ""]
    open_ids = []
    for case in d["cases"]:
        open_ids += [u for u in case["unresolved_ids"] if u not in open_ids]
    for u in open_ids + ["u-i-effective-bandwidth", "u-i-latency", "u-i-pcie-primary"]:
        if u in unresolved:
            out.append(f"- `{u}`: {unresolved[u]['question']} Needed: {unresolved[u]['next_evidence_needed']}")
    out += ["", "## 10. IDE-010 workflow B requirements", "",
            f"All {len(reqs)} requirements of workflow {wf['letter']} ({wf['title']}).", "",
            "| Requirement | Coverage here | Note | Figures |", "| --- | --- | --- | --- |"]
    for m in d["workflow_b_mapping"]:
        out.append(f"| `{m['requirement_id']}` {cell(reqs[m['requirement_id']]['title'])} | {COVERAGE[m['coverage']]} | {cell(m['note'])} | "
                   f"{', '.join(f'`{x}`' for x in m['figure_ids']) or '—'} |")
    out += ["", "## 11. Independent technical review", "",
            "No review has taken place and no reviewer is assigned. Before any classification supports a public statement:", "",
            "- a reviewer reads each figure's passage in its source and confirms value, unit, direction and scope;",
            "- a reviewer checks each normalization rule and its preconditions, and each classification against them;",
            "- the questions in the expert-review brief (`BANDWIDTH_EXPERT_REVIEW_BRIEF_012.md`) are put to specialists who volunteer, one question at a time;",
            "- no answer is recorded as review unless the reviewer has agreed to how, and under what name, it is recorded.", "",
            "## 12. Source lineage, dates and limitations", "",
            "| Source | Publisher | Type | Published | Latest inspection |", "| --- | --- | --- | --- | --- |"]
    for sid in sorted({f["source_id"] for f in d["figures"]}):
        s = reg[sid]
        out.append(f"| `{sid}` | {cell(s['publisher'])} | {word(s['source_type'])} | {s.get('publication_date') or '—'} | {inspection(last.get(sid))} |")
    out += ["", "- Every figure is a published statement or arithmetic on one; no measurement was made or reviewed.",
            "- Passage checks show that text is still published, not that a figure is correct or current.",
            "- Classifications and readings are AI-assisted and have not been reviewed by a person.",
            f"- Public reference: {d['public_reference_decision']['reason']}", "",
            "## 13. Research applications", ""]
    out += [f"- {a}." for a in d["applications"]]
    out += ["", "Lineage: judgments in `data/research/institutional/accelerator-bandwidth-comparability-dossier-012.json`; figures through "
            "releases 001 and 004 and `data/evidence-conflicts.json`; validated by `scripts/validate_bandwidth_dossier.py`; regenerated by "
            "`scripts/render_bandwidth_dossier.py`.", ""]
    return "\n".join(out)


def render_brief(d, ctx) -> str:
    reg = ctx["registry"]
    out = [HEADER, "", "# Expert Review Brief — Accelerator Bandwidth Comparability (IDE-012)", "",
           "This brief invites specialists in semiconductor memory and accelerator interconnects to review one bounded question each, "
           "using public material only. It accompanies the research dossier `ACCELERATOR_BANDWIDTH_COMPARABILITY_DOSSIER_012.md`, "
           "which is an AI-assisted research candidate and has not been reviewed by any person.", "",
           "## Terms", "",
           "- Participation is voluntary and unpaid. There is no deadline and no obligation to answer every question.",
           "- You may review a single question. Disagreement, criticism and \"this cannot be settled from public material\" are all useful answers.",
           "- Use only public, non-confidential material. Please do not share anything under NDA or not yet published.",
           "- You will be named only if you give explicit permission, and only in the form you approve. Otherwise your contribution is recorded without attribution.",
           "- A response is recorded as a specialist's comment on the question it answers. It is not represented as validation of the dossier, "
           "and AI-assisted analysis in the dossier is never presented as independent human review.", "",
           "## Questions", ""]
    for n, q in enumerate(d["review_questions"], start=1):
        out += [f"### {n}. {q['question']}", "", f"- **Why it matters:** {q['why_it_matters']}",
                f"- **What would settle it:** {q['would_settle']}"]
        if q["materials"]:
            out.append("- **Public materials:** " + "; ".join(f"{reg[s]['publisher']}, “{reg[s]['title']}” ({reg[s].get('publication_date') or 'undated'}), {reg[s]['canonical_url']}" for s in q["materials"]))
        else:
            out.append("- **Public materials:** none identified; pointing to any would itself help.")
        if q["case_id"]:
            out.append(f"- **Dossier section:** case `{q['case_id']}`.")
        out.append("")
    return "\n".join(out)


def outputs() -> dict[Path, str]:
    d, ctx = json.loads(v.DOSSIER.read_text(encoding="utf-8")), v.load_context()
    return {OUT: render_dossier(d, ctx), BRIEF: render_brief(d, ctx)}


def out_of_sync() -> list[str]:
    return [p.name for p, text in outputs().items() if not p.is_file() or p.read_text(encoding="utf-8") != text]


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a document does not match its inputs")
    args = parser.parse_args(argv)
    if args.check:
        stale = out_of_sync()
        if stale:
            print(f"FAIL: out of date: {', '.join(stale)}; run scripts/render_bandwidth_dossier.py", file=sys.stderr)
            raise SystemExit(1)
        print("PASS: bandwidth dossier and review brief match their inputs.")
        return
    for path, text in outputs().items():
        path.write_text(text, encoding="utf-8")
    print("bandwidth dossier and brief rendered")


if __name__ == "__main__":
    main()
